import { test, expect } from "@playwright/test";
import { Client, Users } from "node-appwrite";
import { randomBytes } from "node:crypto";
import { generate } from "otplib";
import { AppwriteStore, storageId } from "../src/lib/appwrite-store";

test("registrazione dall'app, MFA, dati e passkey contro Appwrite reale", async ({ page, context }) => {
  test.setTimeout(90000);
  const base = process.env.TEST_APP_URL || "http://127.0.0.1:3002";
  const email = "integration-helpme@example.invalid";
  const password = randomBytes(24).toString("base64url");
  const id = storageId("owner", email);
  const client = new Client().setEndpoint(process.env.APPWRITE_ENDPOINT!).setProject(process.env.APPWRITE_PROJECT_ID!).setKey(process.env.APPWRITE_API_KEY!);
  const users = new Users(client);
  const store = new AppwriteStore(client, process.env.APPWRITE_DATABASE_ID || "helpme");
  expect(await store.get("app_owner", "singleton"), "Il test non puo sostituire un proprietario esistente").toBeNull();
  const previous = await users.get({ userId: id }).catch(error => { if (error.code === 404) return null; throw error; });
  expect(previous, "Il test non puo sostituire un utente esistente").toBeNull();
  try {
    await page.goto(base);
    await page.getByRole("button", { name: "Crea account personale", exact: true }).click();
    await page.getByLabel("Email", { exact: true }).fill(email);
    await page.getByLabel("Password", { exact: true }).fill(password);
    await page.getByLabel("Conferma password", { exact: true }).fill(password);
    await page.getByRole("button", { name: "Crea account", exact: true }).click();
    await expect(page.getByRole("heading", { name: "Conferma la tua email", exact: true })).toBeVisible();
    const saved = await store.get("app_owner", "singleton");
    expect(saved?.user_id).toBe(id);
    expect(saved?.email).toBe(email);
    expect((await context.request.get(base + "/api/data")).status()).toBe(403);
    const repeat = await context.request.post(base + "/api/registration", { headers: { Origin: base }, data: { email, password } });
    expect(repeat.status()).toBe(409);
    await users.updateEmailVerification({ userId: id, emailVerification: true });
    await page.getByRole("button", { name: "Ho confermato l'email", exact: true }).click();
    await expect(page.getByRole("heading", { name: "Proteggi il tuo account", exact: true })).toBeVisible();
    const denied = await context.request.get(base + "/api/data");
    expect(denied.status()).toBe(403);
    await page.getByRole("button", { name: "Configura Authenticator", exact: true }).click();
    await expect(page.locator(".qr")).toBeVisible();
    const secret = await page.locator("code.secret").textContent();
    expect(secret).toBeTruthy();
    await page.getByLabel("Codice Authenticator", { exact: true }).fill(await generate({ secret: secret! }));
    await page.getByRole("button", { name: "Verifica e accedi", exact: true }).click();
    await expect(page.getByRole("heading", { name: "Panoramica", exact: true })).toBeVisible();
    const sessionCookie = (await context.cookies()).find(cookie => cookie.name.startsWith("a_session_"));
    expect(sessionCookie?.httpOnly).toBe(true);
    expect((await context.request.get(base + "/api/data")).status()).toBe(200);
    await page.getByRole("button", { name: "Aggiungi movimento", exact: true }).click();
    await page.getByLabel("Descrizione", { exact: true }).fill("Spesa sintetica migrazione");
    await page.getByLabel("Importo EUR", { exact: true }).fill("30,00");
    await page.getByLabel("Categoria", { exact: true }).selectOption("Ristoranti");
    await page.getByRole("button", { name: "Salva movimento", exact: true }).click();
    await expect(page.getByRole("dialog")).not.toBeVisible();
    expect((await store.list("transactions")).some(row => row.user_id === id && row.description === "Spesa sintetica migrazione")).toBe(true);
    const cdp = await context.newCDPSession(page);
    await cdp.send("WebAuthn.enable");
    await cdp.send("WebAuthn.addVirtualAuthenticator", { options: { protocol: "ctap2", transport: "internal", hasResidentKey: true, hasUserVerification: true, isUserVerified: true, automaticPresenceSimulation: true } });
    await page.locator("nav").getByRole("button", { name: "Sicurezza", exact: true }).click();
    await page.getByRole("button", { name: "Registra passkey", exact: true }).click();
    await expect(page.getByRole("status")).toContainText("Passkey registrata");
    await page.getByRole("button", { name: "Esci", exact: true }).click();
    await expect(page.getByRole("heading", { name: "Bentornato", exact: true })).toBeVisible();
    await page.getByRole("button", { name: "Accedi con passkey", exact: true }).click();
    await expect(page.getByRole("heading", { name: "Verifica il tuo accesso", exact: true })).toBeVisible();
    expect((await context.request.get(base + "/api/data")).status()).toBe(401);
    await page.getByLabel("Codice Authenticator", { exact: true }).fill(await generate({ secret: secret! }));
    await page.getByRole("button", { name: "Verifica e accedi", exact: true }).click();
    await expect(page.getByRole("heading", { name: "Panoramica", exact: true })).toBeVisible();
  } finally {
    for (const entity of ["transactions", "auth_sessions", "passkeys", "webauthn_challenges"]) for (const row of await store.list(entity)) if (row.user_id === id) await store.remove(entity, row.id);
    const owner = await store.get("app_owner", "singleton");
    if (owner?.user_id === id) await store.remove("app_owner", "singleton");
    await users.delete({ userId: id }).catch(error => { if (error.code !== 404) throw error; });
  }
});